const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    return (localStorage.getItem('dhd-language') as Language) || 'ar';
  });

  const setLanguage = useCallback((lang: Language) => {
    localStorage.setItem('dhd-language', lang);
    setLanguageState(lang);
  }, []);

  const dir = language === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = language;
  }, [dir, language]);

  const t = useCallback((key: string, params?: Record<string, string | number>) => {
    let str = (translations[language] as Record<string, string>)[key] || (translations['en'] as Record<string, string>)[key] || key;
    if (params) {
      Object.keys(params).forEach(p => {
        str = str.replace(new RegExp(`{${p}}`, 'g'), String(params[p]));
      });
    }
    return str;
  }, [language]);

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (context === undefined) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
};
